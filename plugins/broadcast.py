@Client.on_message(filters.command("broadcast") & filters.user(ADMINS) & filters.private)
async def broadcast_users(bot, message):
    if not message.reply_to_message:
        return await message.reply("<b>Reply to a message to broadcast.</b>",parse_mode=enums.ParseMode.HTML)
    if lock.locked():
        return await message.reply("⚠️ Another broadcast is in progress. Please wait...")
    ask = await message.reply(
        "<b>Do you want to pin this message in users?</b>",
        reply_markup=ReplyKeyboardMarkup([["Yes", "No"]], one_time_keyboard=True, resize_keyboard=True)
    )
    try:
        dreamxbotz_user_response = await bot.listen(chat_id=message.chat.id, user_id=message.from_user.id, timeout=60)
    except asyncio.TimeoutError:
        await ask.delete()
        return await message.reply("❌ Timed out. Broadcast cancelled.")
    await ask.delete()
    if dreamxbotz_user_response.text not in ("Yes", "No"):
        return await message.reply("❌ Invalid input. Broadcast cancelled.")

    is_pin = dreamxbotz_user_response.text == "Yes"
    b_msg = message.reply_to_message
    users = [user async for user in await db.get_all_users()]
    total_users = len(users)
    dreamxbotz_status_msg = await message.reply_text("📤 <b>Broadcasting your message...</b>")
    success = blocked = deleted = failed = 0
    start_time = time.time()
    cancelled = False

    collection = db.db["broadcasts"]
    broadcast_id = str(time.time_ns())
    await collection.insert_one({
        "broadcast_id": broadcast_id,
        "type": "meta",
        "status": "running",
        "cancel_requested": False,
        "created_at": time.time()
    })

    async def send(user):
        chat_id = int(user["id"])
        try:
            sent = await b_msg.copy(chat_id=chat_id)
            record = await collection.insert_one({
                "broadcast_id": broadcast_id,
                "type": "message",
                "chat_id": chat_id,
                "message_id": sent.id
            })
            state = await collection.find_one({"broadcast_id": broadcast_id, "type": "meta"})
            if state and state.get("cancel_requested"):
                try:
                    await bot.delete_messages(chat_id, sent.id)
                    await collection.delete_one({"_id": record.inserted_id})
                except Exception:
                    logging.exception(f"Could not delete just-sent broadcast from {chat_id}")
                return "Cancelled"
            if is_pin:
                await sent.pin(both_sides=True)
            return "Success"
        except FloodWait as e:
            await asyncio.sleep(e.value)
            try:
                sent = await b_msg.copy(chat_id=chat_id)
                record = await collection.insert_one({
                    "broadcast_id": broadcast_id,
                    "type": "message",
                    "chat_id": chat_id,
                    "message_id": sent.id
                })
                state = await collection.find_one({"broadcast_id": broadcast_id, "type": "meta"})
                if state and state.get("cancel_requested"):
                    try:
                        await bot.delete_messages(chat_id, sent.id)
                        await collection.delete_one({"_id": record.inserted_id})
                    except Exception:
                        logging.exception(f"Could not delete just-sent broadcast from {chat_id}")
                    return "Cancelled"
                if is_pin:
                    await sent.pin(both_sides=True)
                return "Success"
            except Exception:
                logging.exception(f"Error retrying broadcast to {chat_id}")
                return "Error"
        except Exception as e:
            logging.exception(f"Error sending broadcast to {chat_id}")
            return "Blocked" if "USER_IS_BLOCKED" in str(e) else "Error"

    async with lock:
        for i in range(0, total_users, 100):
            broadcast_state = await collection.find_one({"broadcast_id": broadcast_id, "type": "meta"})
            if broadcast_state and broadcast_state.get("cancel_requested"):
                cancelled = True
                break
            if temp.B_USERS_CANCEL:
                temp.B_USERS_CANCEL = False
                cancelled = True
                break
            batch = users[i:i + 100]
            results = await asyncio.gather(*[send(user) for user in batch])

            for res in results:
                if res == "Success":
                    success += 1
                elif res == "Blocked":
                    blocked += 1
                elif res == "Deleted":
                    deleted += 1
                elif res == "Error":
                    failed += 1

            done = i + len(batch)
            elapsed = get_readable_time(time.time() - start_time)
            await dreamxbotz_status_msg.edit(
                f"📣 <b>Broadcast Progress....:</b>\n\n"
                f"👥 Total: <code>{total_users}</code>\n"
                f"✅ Done: <code>{done}</code>\n"
                f"📬 Success: <code>{success}</code>\n"
                f"⛔ Blocked: <code>{blocked}</code>\n"
                f"🗑️ Deleted: <code>{deleted}</code>\n"
                f"⏱️ Time: {elapsed}",
                reply_markup=InlineKeyboardMarkup([
                    [InlineKeyboardButton("❌ CANCEL", callback_data="broadcast_cancel#users")]
                ])
            )
            await asyncio.sleep(0.1)
    elapsed = get_readable_time(time.time() - start_time)
    final_status = (
        f"{'❌ <b>Broadcast Cancelled.</b>' if cancelled else '✅ <b>Broadcast Completed.</b>'}\n\n"
        f"🕒 Time: {elapsed}\n"
        f"👥 Total: <code>{total_users}</code>\n"
        f"📬 Success: <code>{success}</code>\n"
        f"⛔ Blocked: <code>{blocked}</code>\n"
        f"🗑️ Deleted: <code>{deleted}</code>\n"
        f"❌ Failed: <code>{failed}</code>"
    )
    await collection.update_one(
        {"broadcast_id": broadcast_id, "type": "meta", "status": {"$nin": ["deleting", "deleted", "delete_failed"]}},
        {"$set": {"status": "cancelled" if cancelled else "completed"}}
    )
    await dreamxbotz_status_msg.edit(final_status)


@Client.on_message(filters.command("delbroadcast") & filters.user(ADMINS) & filters.private)
async def delete_broadcast(bot, message):
    collection = db.db["broadcasts"]
    latest = await collection.find_one(
        {"type": "meta", "status": {"$nin": ["deleted"]}},
        sort=[("_id", -1)]
    )
    if not latest:
        return await message.reply("No broadcast messages found to delete.")

    broadcast_id = latest["broadcast_id"]
    await collection.update_one(
        {"broadcast_id": broadcast_id, "type": "meta"},
        {"$set": {"cancel_requested": True, "status": "deleting"}}
    )
    status = await message.reply("🗑️ Deleting the latest broadcast from users' chats...")
    deleted_count = failed_count = 0

    async for record in collection.find({"broadcast_id": broadcast_id, "type": "message"}):
        try:
            await bot.delete_messages(int(record["chat_id"]), int(record["message_id"]))
            await collection.delete_one({"_id": record["_id"]})
            deleted_count += 1
        except Exception as e:
            logging.exception(f"Failed to delete broadcast message for {record['chat_id']}: {e}")
            failed_count += 1

    await collection.update_one(
        {"broadcast_id": broadcast_id, "type": "meta"},
        {"$set": {"status": "deleted" if failed_count == 0 else "delete_failed"}}
    )
    await status.edit(
        f"✅ <b>Broadcast deletion finished.</b>\n"
        f"🗑️ Deleted: <code>{deleted_count}</code>\n"
        f"❌ Failed: <code>{failed_count}</code>"
    )


@Client.on_message(filters.command("grp_broadcast") & filters.user(ADMINS) & filters.private)
async def broadcast_group(bot, message):
    if not message.reply_to_message:
        return await message.reply("<b>Reply to a message to group broadcast.</b>", parse_mode=enums.ParseMode.HTML)
    ask = await message.reply(
        "<b>Do you want to pin this message in groups?</b>",
        reply_markup=ReplyKeyboardMarkup([["Yes", "No"]], one_time_keyboard=True, resize_keyboard=True)
    )
    try:
        dreamxbotz_user_response = await bot.listen(chat_id=message.chat.id, user_id=message.from_user.id, timeout=60)
    except asyncio.TimeoutError:
        await ask.delete()
        return await message.reply("❌ Timed out. Broadcast cancelled.")
    await ask.delete()
    if dreamxbotz_user_response.text not in ("Yes", "No"):
        return await message.reply("❌ Invalid input. Broadcast cancelled.")

    is_pin = dreamxbotz_user_response.text == "Yes"
    b_msg = message.reply_to_message
    chats = await db.get_all_chats()
    total_chats = await db.total_chat_count()
    dreamxbotz_status_msg = await message.reply_text("📤 <b>Broadcasting your message to groups...</b>")
    start_time = time.time()
    done = success = failed = 0
    cancelled = False

    async with lock:
        async for chat in chats:
            time_taken = get_readable_time(time.time() - start_time)
            if temp.B_GROUPS_CANCEL:
                temp.B_GROUPS_CANCEL = False
                cancelled = True
                break
            try:
                sts = await groups_broadcast(int(chat['id']), b_msg, is_pin)
            except Exception as e:
                logging.exception(f"Error broadcasting to group {chat['id']}")
                sts = 'Error'
            if sts == "Success":
                success += 1
            else:
                failed += 1
            done += 1
            if done % 10 == 0:
                btn = [[InlineKeyboardButton("❌ CANCEL", callback_data="broadcast_cancel#groups")]]
                await dreamxbotz_status_msg.edit(
                    f"📣 <b>Group broadcast progress:</b>\n\n"
                    f"👥 Total Groups: <code>{total_chats}</code>\n"
                    f"✅ Completed: <code>{done} / {total_chats}</code>\n"
                    f"📬 Success: <code>{success}</code>\n"
                    f"❌ Failed: <code>{failed}</code>",
                    reply_markup=InlineKeyboardMarkup(btn)
                )
    time_taken = get_readable_time(time.time() - start_time)
    dreamxbotz_text = (
        f"{'❌ <b>Groups broadcast cancelled!</b>' if cancelled else '✅ <b>Group broadcast completed.</b>'}\n"
        f"⏱️ Completed in {time_taken}\n\n"
        f"👥 Total Groups: <code>{total_chats}</code>\n"
        f"✅ Completed: <code>{done} / {total_chats}</code>\n"
        f"📬 Success: <code>{success}</code>\n"
        f"❌ Failed: <code>{failed}</code>"
    )
    try:
        await dreamxbotz_status_msg.edit(dreamxbotz_text)
    except MessageTooLong:
        with open("reason.txt", "w+") as outfile:
            outfile.write(str(failed))
        await message.reply_document(
            "reason.txt", caption=dreamxbotz_text
        )
        os.remove("reason.txt")

